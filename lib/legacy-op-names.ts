/**
 * **旧操作名的兼容映射**（阶段 4，2026-09-12）。
 *
 * ## 为什么单独一个文件
 *
 * 别名表本身是一份契约，而且它只会**越来越短**——存量旧数据渐渐淘汰之后，
 * 这张表就该被删掉。放独立文件，**删掉它 = 兼容期结束**，是一个看得见的动作，
 * 不会埋在别的模块里被遗忘。
 *
 * ## 它解决的是什么
 *
 * 改名（`update_card` → `update_item` 等）之后，**历史上落盘的 ChangeSet
 * 里仍然写着旧名**。那些数据要能永远读得懂（用户裁决：读取长期兼容、写入只写新名）。
 *
 * ## 数据事实（2026-09-12 实测，两个后端都查了）
 *
 * | 后端 | 旧名出现 | 其中 `add_card`/`remove_card` |
 * |---|---:|---|
 * | 文件 `.sitecraft-data/sites` | 288 | **0 / 0** |
 * | Postgres `sitecraft_sites` | 398 | **0 / 0** |
 *
 * 所以实际上**只有 `update_card` 一个名字**有真实存量；
 * 另两个名字仍登记在此，是为了**万一有第三批数据**（见下）时不至于读不进来。
 *
 * ## 落盘数据不迁移
 *
 * 写入侧只 append 新 ChangeSet，**从不回写旧条目**——所以旧名会永远留在历史里。
 * 这是**有意**的：读取侧认得就行，没必要去改写用户的历史。
 * 想要"干净的落盘"需要一次显式迁移，那是另一个决策，不在本机制内。
 */

/**
 * 旧名 → 新名。**这是全仓库唯一的别名事实源**，不要在别处另写一份。
 *
 * ⚠️ 新增条目时**只加不删**：删掉一条 = 那批旧数据再也读不进来。
 *
 * ⚠️⚠️ **这张表里的旧名是"历史值"，不是"当前值"——不要跟着改名一起改掉它。**
 * 2026-09-12 改名时用盲替换（`sed` 全线替换 `update_card`）时，
 * 这张表和两个调研脚本的 `LEGACY_OPS` 一起被打成了新名，
 * 于是"旧名 → 新名"变成了"新名 → 新名"——**兼容层会静默变成空操作**，
 * 而且测试还是绿的（因为新名本来就能读）。
 * 凡是要动这些字符串，先确认你改的是**目标名**而不是**来源名**。
 */
export const LEGACY_OPERATION_NAMES: Readonly<Record<string, string>> = Object.freeze({
  update_card: "update_item",
  add_card: "add_item",
  remove_card: "remove_item",
});

/** 把单个操作名的旧名换成新名；不是旧名就原样返回。 */
export function currentOperationName(op: unknown): unknown {
  if (typeof op !== "string") return op;
  return LEGACY_OPERATION_NAMES[op] ?? op;
}
